// ── Photographing the Amazon panel ────────────────────────────────────────────────────────────
//
// Drives the real index.html / app.js / style.css and photographs the Amazon panel in the three
// states the phase has to be shown in: a draft filled from what the AI wrote, the same draft with
// what Amazon requires still missing, and the result of a sandbox submission.
//
// TWO THINGS ARE STUBBED HERE, AND BOTH ARE STUBBED FOR A STATED REASON.
//
//   1. THE SERVER. The desktop build binds http://localhost:9332 and nothing else — the eBay OAuth
//      relay redirects there — and on this machine 9332 sits inside a Windows reserved port range
//      (9248-9347), so the app cannot bind it at all. What is served below is therefore the same
//      wwwroot the app serves, off disk, on a port that is free. The HTML, the CSS and the
//      JavaScript in these screenshots are the shipped files, unmodified.
//
//   2. THE AMAZON RESPONSES. This deployment cannot obtain an Amazon access token: the stored LWA
//      client secret is a placeholder note and LWA answers it with invalid_client. So the panel
//      cannot be driven to a filled state by asking Amazon. The bodies served for /api/amazon/*
//      are NOT hand-written to look right — they are generated by AmazonUiFixtureTests from the
//      real mapper reading the real captured draft onto the schema fixture, and serialized through
//      the endpoints' own Describe(). Regenerate them with:
//
//        dotnet test --filter FullyQualifiedName~AmazonUiFixtureTests
//
// Every other /api/* call the app boot makes is answered with an empty object. Those drive parts of
// the screen that are not being photographed, and a stub there cannot make the Amazon panel look
// better than it is.
//
// Run:  node amazon-ui-capture.mjs

import { createServer } from 'node:http';
import { readFile, readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// fileURLToPath, not .pathname — the repo folder has a space in it and .pathname hands back %20.
const ROOT     = fileURLToPath(new URL('.', import.meta.url));
const WWWROOT  = join(ROOT, 'ING eBay AutoLister', 'wwwroot');
const FIXTURES = join(ROOT, 'verification', 'amazon-ui');
const OUT      = join(ROOT, 'verification', 'amazon-ui');
const PORT     = 9411;

const playwright = await import(
  'file:///' + join(process.env.APPDATA, 'npm', 'node_modules', 'playwright', 'index.mjs').replace(/\\/g, '/'));

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js':   'text/javascript; charset=utf-8',
  '.css':  'text/css; charset=utf-8',
  '.svg':  'image/svg+xml',
  '.png':  'image/png',
};

// ── The real assets, off disk ────────────────────────────────────────────────
const server = createServer(async (req, res) => {
  const path = decodeURIComponent(req.url.split('?')[0]);
  const file = join(WWWROOT, path === '/' ? 'index.html' : path.replace(/^\//, ''));
  if (!existsSync(file)) { res.writeHead(404).end('not found'); return; }
  res.writeHead(200, { 'Content-Type': TYPES[extname(file)] || 'application/octet-stream' });
  res.end(await readFile(file));
});
await new Promise(r => server.listen(PORT, '127.0.0.1', r));
console.log(`serving the real wwwroot on http://127.0.0.1:${PORT}`);

const fixture = async name => JSON.parse(await readFile(join(FIXTURES, name), 'utf8'));

const FILL_MISSING = await fixture('fill-missing.json');
const FILL_READY   = await fixture('fill-ready.json');
const SUBMISSION   = await fixture('submission-pending.json');
const STATUS       = await fixture('status.json');

// Which fill the panel is looking at. Flipped between shots.
let currentFill = FILL_MISSING;

// The draft the fixtures were generated from, so the form on screen and the answer beside it are
// about the same item. Taken from AmazonListingFillFixtures.RealDraftFile.
const DRAFT = {
  'nl-title':    'Bitaxe NerdQaxe++ 4.8TH/s BM1370 Bitcoin Solo Miner SHA-256 ASIC w/ Fan',
  'nl-brand':    'NerdQaxe',
  'nl-mpn':      'NerdQaxe++',
  'nl-price':    '549.99',
  'nl-quantity': '20',
};

// A hung selector here used to leave the process alive holding the port, so the next run died on
// EADDRINUSE and the screenshots on disk were half from one run and half from another.
const deadline = setTimeout(() => {
  console.error('capture exceeded its own deadline — exiting so the port is released');
  process.exit(1);
}, 8 * 60 * 1000);
deadline.unref?.();

const browser = await playwright.chromium.launch();

async function shot(name, width, height, steps) {
  const context = await browser.newContext({
    viewport: { width, height },
    deviceScaleFactor: 2,
  });
  const page = await context.newPage();

  await page.route('**/api/**', async route => {
    const url = route.request().url();
    const json = body => route.fulfill({
      status: 200, contentType: 'application/json', body: JSON.stringify(body),
    });

    if (url.includes('/api/amazon/status'))        return json(STATUS);
    if (url.includes('/api/amazon/listing-fill'))  return json(currentFill);
    if (url.includes('/api/amazon/product'))       return json(SUBMISSION);
    // Everything else the boot asks for. Not photographed; cannot flatter the panel.
    return json({});
  });

  await page.goto(`http://127.0.0.1:${PORT}/index.html`, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1200);

  // Onboarding and any first-run overlay out of the way — this is a photograph of one panel.
  await page.evaluate(() => {
    document.querySelectorAll('.onboarding-overlay, #onboarding-overlay, .modal-backdrop')
      .forEach(el => el.classList.add('hidden'));
  });

  // Into the listing screen the way a seller gets there.
  await page.click('#btn-new-ai-listing').catch(() => {});
  await page.waitForSelector('#new-listing-overlay:not(.hidden)', { timeout: 8000 });
  await page.waitForTimeout(400);

  for (const [id, value] of Object.entries(DRAFT)) {
    await page.fill('#' + id, value).catch(() => {});
  }
  await page.waitForTimeout(200);

  await steps(page);

  await mkdir(OUT, { recursive: true });
  const file = join(OUT, `${name}.png`);
  await page.screenshot({ path: file });
  console.log('  wrote', file);
  await context.close();
}

// The panel, with what Amazon requires and the draft does not answer.
const toAmazon = async page => {
  await page.click('#nl-market-amazon');
  await page.waitForTimeout(900);
  // Open the list — the reasons are the point of the shot.
  const open = await page.getAttribute('#nl-amz-toggle', 'aria-expanded');
  if (open !== 'true') await page.click('#nl-amz-toggle');
  await page.waitForTimeout(500);
  // The action cards at the top of the listing screen are not what is being shown. Collapsing the
  // scroller puts the form and the panel in one frame instead of one of them below the fold.
  await page.evaluate(() => {
    document.querySelector('.nl-url-section')?.classList.add('hidden');
    document.querySelector('#nl-sold-comps-strip')?.classList.add('hidden');
  });
  await page.waitForTimeout(400);
  await page.locator('#nl-amz').scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
};

for (const [w, h, tag] of [[1440, 1150, '1440'], [390, 900, '390']]) {
  console.log(`\n── ${w}px ──`);

  currentFill = FILL_MISSING;
  await shot(`amazon_missing_${tag}`, w, h, toAmazon);

  currentFill = FILL_READY;
  await shot(`amazon_filled_${tag}`, w, h, toAmazon);

  currentFill = FILL_READY;
  await shot(`amazon_submitted_${tag}`, w, h, async page => {
    await toAmazon(page);
    await page.fill('#nl-amz-sku', 'ING-NERDQAXE-001');
    await page.click('#nl-btn-amz-submit');
    await page.waitForTimeout(900);
    await page.locator('#nl-result-msg').scrollIntoViewIfNeeded();
    await page.waitForTimeout(300);
  });
}

await browser.close();
server.close();
console.log('\ndone');
